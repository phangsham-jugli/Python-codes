#rev()
days_of_week=["mon","tue","wed","thur","fri","sat","sun"]
days_of_week.reverse()
print(days_of_week)
print("\n")

#sort()
nums=[6,7,1,2,8,10,3,4,22,2]
nums.sort()
print(nums)
print("\n")
nums.sort(reverse=True) #descending order
print(nums)
print("\n")

#count()
print(f"the total number of 2 appear in list is:{nums.count(2)}\n")

