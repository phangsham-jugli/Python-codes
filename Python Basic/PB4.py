#Arithmetic & Assignment Operators
num1=10
num2=5

# + -> Addition operator
r1=num1+num2
print(r1)

# - ->Substraction operator
r2=num1-num2
print(r2)

# * ->Multiplication operator
r3=num1*num2
print(r3)

# / ->Division operator
r4=num1/num2  #result will be in float
print(r4)

# // -> Floor division
r5=num1//num2  #result will be in int
print(r5)

# % ->modulus
print(10%3)

# ** ->exponent
print(3**3)

#compound operator
x=10
x += 2
print(x)

x -= 1
print(x)

x *= 3
print(x)

x /= 3
print(x)