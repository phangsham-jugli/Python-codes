#Tuple Indexing
# Print:
# The first fruit
# The last fruit
# The index of "orange","mango"
fruits = ("apple", "banana", "mango", "orange", "grapes")

print(fruits[0]) #first fruit
print(fruits[-1]) #last fruit
print(f'index of orange is:{fruits.index("orange")} and index of mango is:{fruits.index("mango")}')