#Tuple Slicing

# Using slicing, print:
# First 3 numbers
# Last 3 numbers
# Numbers from index 2 to 5
# Every second element

numbers = (10, 20, 30, 40, 50, 60, 70)
print(numbers[0:3]) #printing first 3 element
print(numbers[4:7]) #last three numbers
print(numbers[2:6:1]) #printing from index 2 to 5
print(numbers[0:7:2]) #every second element