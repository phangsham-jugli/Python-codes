fruits = ["apple", "banana", "mango", "orange", "grapes"]

#First 3 fruits
print(fruits[0:3])
print("\n")

#last 2 fruits
print(fruits[3:])
print("\n")

#fruits in reverse order
fruits.reverse()
print(fruits)
print("\n")

#every second fruit
print(fruits[0:6:2])
print("\n")

#repeat the list twice

print(fruits *2)