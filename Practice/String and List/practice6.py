# Find:
# Total marks
# Average marks
# Highest mark
# Lowest mark
# Number of students who scored more than 60
marks = [45, 67, 89, 34, 76, 90, 55]
print("\n")

total=sum(marks)
print(f"the total marks is:{total}")
print("\n")

average=int(total/7)
print(f"the average marks is:{average}")
print("\n")

h=max(marks)
print(f"the higest marks is:{h}\n")

l=min(marks)
print(f"the lowest marks is:{l}\n")

