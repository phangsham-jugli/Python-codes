#THE RANGE() FUNCTION\
#to print 1 to 10 using range()
print("Natural number from 1 to 10:")
for i in range(1,11):
    print(i)

print("Eng of loop!\n")

#to print odd from 1 to 10 using only range()
print("Odd number between 1 to 10:")
for a in range(1,11,2):
    print(a)

print("Eng of loop!\n")

# to print even from 1 to 10 using only range()
print("Even number from 1 to 10:")
for a in range(2, 11, 2):
    print(a)

print("Eng of loop!\n")

#to print number in reverse from 10 to 1 using only range()
print("Reverse number form 10 to 1:")
for a in range(10,0,-1):
    print(a)

print("Eng of loop\n")